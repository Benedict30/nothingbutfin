#!/usr/bin/env node
/*
 * analytics.js — visitors and story readership from data/events.jsonl (anonymous visitor ids).
 *   PV = page views (or story opens), UV = unique visitors, UV/PV and PV/UV.
 *
 *   node scripts/analytics.js [days]      default 30; on the server: docker exec fsv node scripts/analytics.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(__dirname, '..', 'data'));
const days = +process.argv[2] || 30;
const since = new Date(Date.now() - days * 86400e3).toISOString();

const read = name => {
  try { return fs.readFileSync(path.join(DATA_DIR, name), 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l)); } catch { return []; }
};
const events = read('events.jsonl').filter(e => e.t >= since);
const usage = read('usage.jsonl').filter(u => u.t >= since);

const pad = (s, n) => String(s).padEnd(n);
const ratio = (a, b) => (b ? (a / b).toFixed(2) : '—');
/** PV, UV and both ratios for a list of events. */
const stats = list => { const pv = list.length, uv = new Set(list.map(e => e.v)).size; return { pv, uv, uvpv: ratio(uv, pv), pvuv: ratio(pv, uv) }; };
const row = (label, s) => console.log(pad(label, 18) + pad(s.pv, 8) + pad(s.uv, 8) + pad(s.uvpv, 8) + s.pvuv);
const top = (list, key, n = 5) => {
  const groups = {};
  for (const e of list) (groups[key(e)] = groups[key(e)] || []).push(e);
  return Object.entries(groups).map(([k, l]) => [k, stats(l)]).sort((a, b) => b[1].pv - a[1].pv).slice(0, n);
};

const views = events.filter(e => e.type === 'view');
const opens = events.filter(e => e.type === 'story_open');
const made = events.filter(e => e.type === 'story_generate');
const story = e => `${e.ticker} ${e.label || e.period} ${e.freq === 'a' ? 'annual ' : ''}${e.lang}`;

console.log(`Last ${days} days${events.length ? ` (log starts ${read('events.jsonl')[0].t.slice(0, 10)})` : ' (no events logged yet)'} · visitors are anonymous browser ids\n`);
console.log(pad('', 18) + pad('PV', 8) + pad('UV', 8) + pad('UV/PV', 8) + 'PV/UV');
row('Site (page views)', stats(views));
row('Story reads', stats(opens));
row('Story generations', stats(made));

if (views.length) {
  const names = new Intl.DisplayNames(['en'], { type: 'region' });
  console.log('\nVisitors by country:');
  for (const [c, s] of top(views, e => e.country || '??', 10)) console.log(`  ${pad(c === '??' ? 'unknown' : names.of(c), 22)} ${s.uv} visitors, ${s.pv} views`);
  console.log('\nMost viewed companies:');
  for (const [t, s] of top(views, e => e.ticker)) console.log(`  ${pad(t, 8)} ${s.pv} views by ${s.uv} visitors`);
}
if (opens.length) {
  console.log('\nMost read stories:');
  for (const [k, s] of top(opens, story)) console.log(`  ${pad(k, 28)} ${s.pv} reads by ${s.uv} visitors`);
  const readers = new Set(opens.map(e => e.v)), visitors = new Set(views.map(e => e.v));
  console.log(`\nShare of visitors who read a story: ${visitors.size ? Math.round((readers.size / visitors.size) * 100) : 0}%`);
}
if (made.length) {
  const langs = {};
  for (const e of made) langs[e.lang] = (langs[e.lang] || 0) + 1;
  console.log(`Stories generated by language: ${Object.entries(langs).map(([l, n]) => `${l} ${n}`).join(', ')}`);
  const reads = new Set(opens.map(story));
  console.log(`Generated stories read at least once afterwards: ${made.filter(e => reads.has(story(e))).length} of ${made.length}`);
}
const storyCost = usage.filter(u => u.feature === 'story').reduce((a, u) => a + (u.cost || 0), 0);
if (storyCost) console.log(`\nStory spend in this window: $${storyCost.toFixed(2)} · per read: $${opens.length ? (storyCost / opens.length).toFixed(3) : '—'}`);

if (views.length) {
  console.log('\nBy day:        PV   UV   story reads');
  const byDay = {};
  for (const e of [...views, ...opens]) (byDay[e.t.slice(0, 10)] = byDay[e.t.slice(0, 10)] || []).push(e);
  for (const d of Object.keys(byDay).sort().slice(-14)) {
    const v = byDay[d].filter(e => e.type === 'view');
    console.log(`  ${d}  ${pad(v.length, 5)}${pad(new Set(v.map(e => e.v)).size, 5)}${byDay[d].length - v.length}`);
  }
}

const notes = read('feedback.jsonl').filter(f => f.t >= since);
console.log(`\nFeedback (${notes.length}):`);
for (const f of notes.slice(-20)) console.log(`  ${f.t.slice(0, 16).replace('T', ' ')} ${f.country || '--'}${f.email ? ' · ' + f.email : ''}${f.page ? ' · ' + f.page : ''}\n    ${f.message.replace(/\s+/g, ' ').slice(0, 300)}`);
