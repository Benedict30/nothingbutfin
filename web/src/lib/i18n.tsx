import { createContext, useContext, useEffect, useState } from 'react'

// Site languages: English plus the largest groups of overseas investors in US stocks.
export type Lang = 'en' | 'zh-Hans' | 'zh-Hant' | 'ja' | 'ko'
/** Short names for the language button; the menu shows the full ones. */
export const LANG_SHORT: Record<Lang, string> = { en: 'EN', 'zh-Hans': '简中', 'zh-Hant': '繁中', ja: '日', ko: '한' }
export const LANGS: [Lang, string][] = [
  ['en', 'English'],
  ['zh-Hans', '简体中文'],
  ['zh-Hant', '繁體中文'],
  ['ja', '日本語'],
  ['ko', '한국어'],
]
const LOCALE: Record<Lang, string> = { en: 'en-US', 'zh-Hans': 'zh-CN', 'zh-Hant': 'zh-TW', ja: 'ja-JP', ko: 'ko-KR' }
const KEY = 'fsv-lang'

/** Saved choice, else the browser's language. */
function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY)
    if (LANGS.some(([k]) => k === saved)) return saved as Lang
  } catch { /* storage unavailable */ }
  for (const l of navigator.languages ?? [navigator.language]) {
    const s = l.toLowerCase()
    if (/^zh-(tw|hk|mo|hant)/.test(s)) return 'zh-Hant'
    if (s.startsWith('zh')) return 'zh-Hans'
    if (s.startsWith('ja')) return 'ja'
    if (s.startsWith('ko')) return 'ko'
    if (s.startsWith('en')) return 'en'
  }
  return 'en'
}

// The current language for plain functions (t, dates); components re-render through useLang().
let current: Lang = detect()
export const locale = () => LOCALE[current]

type Dict = Record<string, string>
/** Translated UI text; English text is the key. `{name}` placeholders are filled from vars. */
export function t(text: string, vars: Record<string, string | number> = {}) {
  const s = (current === 'en' ? undefined : DICT[current][text]) ?? text
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : ''))
}
/** Line-item name by its key (the server's English name otherwise). */
export const itemName = (key: string, fallback: string) => (current === 'en' ? fallback : ITEMS[current][key] ?? fallback)

/** Dates in the reader's language; ISO dates are calendar days, so read them as UTC. */
export const date = (iso: string, opts: Intl.DateTimeFormatOptions) => new Date(iso.slice(0, 10) + 'T00:00:00Z').toLocaleDateString(locale(), { ...opts, timeZone: 'UTC' })
export const longDate = (iso: string) => date(iso, { dateStyle: 'medium' })
export const shortDate = (iso: string) => date(iso, { year: 'numeric', month: 'numeric', day: 'numeric' })
export const monthName = (m: number) => new Date(Date.UTC(2000, m - 1, 1)).toLocaleDateString(locale(), { month: 'long', timeZone: 'UTC' })
/** "USD" in English; the currency's name elsewhere (美元, 米ドル…). */
export const currencyName = (code: string) => {
  if (current === 'en') return code
  try { return new Intl.DisplayNames([locale()], { type: 'currency' }).of(code) ?? code } catch { return code }
}
export const clockTime = (hhmm: string) => new Date(`2000-01-01T${hhmm}:00`).toLocaleTimeString(locale(), { hour: 'numeric', minute: '2-digit' })

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: current, setLang: () => {} })
export const useLang = () => useContext(Ctx)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current)
  current = lang
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const setLang = (l: Lang) => {
    current = l
    try { localStorage.setItem(KEY, l) } catch { /* storage unavailable */ }
    setLangState(l)
  }
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>
}

